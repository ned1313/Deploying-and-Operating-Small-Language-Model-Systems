#!/usr/bin/env bash
# Module 6 (desktop, WSL): create the application's secrets and the Authelia user list.
#
#   scripts/setup-app-auth.sh            # creates what is missing; never overwrites
#   scripts/setup-app-auth.sh --users    # rebuild users_database.yml (after editing actors.json)
#
# Writes (git-ignored):
#   secrets/authelia/{session_secret,storage_encryption_key,jwt_secret,users_database.yml}
#   secrets/users/password            one demo password for every synthetic user (planning decision 63)
#   secrets/gateway/shared_secret     proves a request came through app-gateway
#   secrets/audit/audit_content_key   Fernet key for captured audit content
# The password is never printed; read it with:  cat secrets/users/password
set -euo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SECRETS="${TACO_SECRETS_DIR:-${REPO}/secrets}"
AUTHELIA_IMAGE="${AUTHELIA_IMAGE:-docker.io/authelia/authelia:4.39.28}"
umask 077
mkdir -p "${SECRETS}/authelia" "${SECRETS}/users" "${SECRETS}/gateway" "${SECRETS}/audit"

random() { head -c 96 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c "$1"; }
create() {  # file, generator...
  local file="$1"; shift
  if [ -s "$file" ]; then echo "  kept    ${file#"${REPO}"/}"; return; fi
  "$@" > "$file"
  echo "  created ${file#"${REPO}"/}"
}

create "${SECRETS}/authelia/session_secret" random 64
create "${SECRETS}/authelia/storage_encryption_key" random 64
create "${SECRETS}/authelia/jwt_secret" random 64
create "${SECRETS}/users/password" random 20
create "${SECRETS}/gateway/shared_secret" random 48
# Fernet: url-safe base64 of 32 random bytes.
create "${SECRETS}/audit/audit_content_key" sh -c "head -c 32 /dev/urandom | base64 | tr '+/' '-_'"

users="${SECRETS}/authelia/users_database.yml"
if [ ! -s "$users" ] || [ "${1:-}" = "--users" ]; then
  # A lighter argon2 cost than the default: CLI, harness, and Locust calls send HTTP Basic on every request.
  digest="$(podman run --rm "$AUTHELIA_IMAGE" authelia crypto hash generate argon2 --iterations 1 \
              --password "$(cat "${SECRETS}/users/password")" | sed -n 's/^Digest: //p')"
  [ -n "$digest" ] || { echo "could not hash the password with ${AUTHELIA_IMAGE}" >&2; exit 1; }
  DIGEST="$digest" python3 - "${REPO}/shared/taco_shared/data/actors.json" > "$users" <<'PY'
import json, os, sys
actors = json.load(open(sys.argv[1], encoding="utf-8"))["actors"]
print("# Generated by scripts/setup-app-auth.sh from shared/taco_shared/data/actors.json. Group = role.")
print("users:")
for actor in actors:
    name = actor["actor_id"]
    print(f"  {name}:")
    print(f"    displayname: {json.dumps(name)}")
    print(f"    password: {json.dumps(os.environ['DIGEST'])}")
    print(f"    email: {json.dumps(name + '@taco.internal')}")
    print(f"    groups: [{json.dumps(actor['role'])}]")
PY
  echo "  wrote   ${users#"${REPO}"/} ($(grep -c 'displayname' "$users") users)"
fi
# The containers read these as non-root users in some images; the folders stay owner-only.
chmod 644 "${SECRETS}"/authelia/* "${SECRETS}"/users/* "${SECRETS}"/gateway/* "${SECRETS}"/audit/*
chmod 700 "${SECRETS}/authelia" "${SECRETS}/users" "${SECRETS}/gateway" "${SECRETS}/audit"
